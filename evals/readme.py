"""Results tables in README.md, generated from the same data as the dashboard.

    uv run python -m evals readme            # rewrite the block between the markers
    uv run python -m evals readme --check    # CI: fail if README.md is out of date

Only the text between RESULTS_START and RESULTS_END is generated. Everything else in the
README is written by hand and must not contain measured numbers.
"""

from pathlib import Path

from evals.dashboard import build

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
RESULTS_START = "<!-- results:start (generated by `uv run python -m evals readme`; don't edit) -->"
RESULTS_END = "<!-- results:end -->"


def pct(x, digits=1) -> str:
    return "n/a" if x is None else f"{100 * x:.{digits}f}%"


def secs(ms) -> str:
    return "n/a" if ms is None else f"{ms / 1000:.1f}s"


def render_results(data: dict) -> str:
    golden, models, guards = data["golden"], data["models"], data["guardrails"]
    e2e, variants, gate, cal = (
        data["end_to_end"],
        data["variants"],
        data["gate"],
        data["calibration"],
    )
    lines = [
        f"Golden set: {golden['n_cases']} cases ({golden['human_reviewed']} human-reviewed so far),"
        f" {golden['smoke']} of them in the CI smoke gate. One run per model, so differences of a"
        " few cases are noise.",
        "",
        f"**Models** (golden suite, guardrails on, pricing as of {models['pricing_as_of']}). "
        f"Source: `{models['source']}`",
        "",
        "| Model | Pass rate | Cost / case | Latency p50 | First text p50 |",
        "|---|---:|---:|---:|---:|",
    ]
    for r in models["rows"]:
        lines.append(
            f"| `{r['model']}` | {pct(r['pass_rate'])} | ${r['cost_per_case_usd']:.4f} "
            f"| {secs(r['latency_p50_ms'])} | {secs(r['ttft_p50_ms'])} |"
        )
    lines += [
        "",
        f"**Guardrails** (held-out test split of small, self-written sets). Source: `{guards['source']}`",
        "",
        "| Guardrail | Recall | False-positive rate | Rules-only recall | Positives / negatives |",
        "|---|---:|---:|---:|---:|",
    ]
    for r in guards["rows"]:
        lines.append(
            f"| {r['guardrail']} | {pct(r['recall'])} | {pct(r['false_positive_rate'])} "
            f"| {pct(r['rules_only_recall'])} | {r['n_positive']} / {r['n_negative']} |"
        )
    lines += [
        "",
        f"**Attacks end to end** (harm checks failed, guardrails off → on). Source: `{e2e['source']}`",
        "",
        "| System prompt | Off | On |",
        "|---|---:|---:|",
    ]
    for s in e2e["scenarios"]:
        lines.append(f"| `{s['prompt']}` | {s['harm_off']}/{s['n']} | {s['harm_on']}/{s['n']} |")
    lines += [
        "",
        f"**Cost variants.** Source: `{variants['source']}`",
        "",
        "| Variant | Pass rate | Measured cost |",
        "|---|---:|---:|",
    ]
    for group, rows in [
        ("routing", variants["routing"]),
        ("caching", variants["caching"]),
        ("trimming", variants["trimming"]),
    ]:
        for r in rows:
            lines.append(
                f"| {group}: {r['name']} | {pct(r['pass_rate'])} ({r['n_passed']}/{r['n_cases']})"
                f" | ${r['cost_usd']:.3f} |"
            )
    x = data.get("experiments")
    if x:
        rel = x["reliability"]
        lines += [
            "",
            f"**Experiments** (`{x['model']}`, judge off; full write-up in `reports/experiments.md`). Source: `{x['source']}`",
            "",
            f"- *Reliability:* the same config run 5 times scored {pct(rel['min'])}–{pct(rel['max'])};"
            f" {len(rel['flaky'])} of {rel['n_cases']} cases flipped between runs, and the smoke subset swung by"
            f" {rel['smoke_swing']} cases (gate limit {rel['gate_limit_cases']}).",
            "",
            "| Prompt (guardrails off) | Pass rate | Attack harm | Grounding failures |",
            "|---|---:|---:|---:|",
        ]
        for r in x["ablation"]:
            lines.append(
                f"| `{r['prompt']}`: {r['what']} | {pct(r['pass_rate'])} | {r['harm']}/{r['harm_n']} | {r['grounding_failures']} |"
            )
        cell = {(d["prompt"], d["guardrails"]): f"{d['harm']}/{d['n']}" for d in x["defense"]}
        lines += [
            "",
            "| Attack harm | Guardrails off | Guardrails on |",
            "|---|---:|---:|",
            f"| full prompt (`v1`) | {cell[('v1', 'off')]} | {cell[('v1', 'on')]} |",
            f"| minimal prompt | {cell[('v1-minimal', 'off')]} | {cell[('v1-minimal', 'on')]} |",
            "",
            "| Effort | Pass rate | Output tokens / case |",
            "|---|---:|---:|",
        ]
        for r in x["effort"]:
            lines.append(
                f"| {r['effort']}{' (mean of ' + str(r['runs']) + ')' if r['runs'] > 1 else ''} | {pct(r['pass_rate'])} | {r['output_tokens_per_case']} |"
            )
    lines += [
        "",
        f"**CI gate baseline:** {pct(gate['pass_rate'])} of {gate['n_cases']} smoke cases "
        f"(`{gate['model']}`, prompt `{gate['prompt_version']}`).",
        "",
    ]
    if cal["rows"]:
        r = cal["rows"][-1]
        lines.append(
            f"**Judge vs human labels** (judge `{r['judge_version']}`, {r['main_dimension']},"
            f" held-out): kappa {r['test_kappa']} (95% CI {r['test_kappa_ci95']}, n={r['test_n']})."
            f" Source: `{cal['source']}`"
        )
    else:
        lines.append(f"**Judge vs human labels:** {cal['status']}.")
    return "\n".join(lines)


def updated_readme(text: str) -> str:
    start, end = text.index(RESULTS_START), text.index(RESULTS_END)
    block = render_results(build())
    return text[: start + len(RESULTS_START)] + "\n\n" + block + "\n\n" + text[end:]


def write(path: Path = README) -> Path:
    path.write_text(updated_readme(path.read_text()))
    return path


def is_current(path: Path = README) -> bool:
    text = path.read_text()
    return text == updated_readme(text)
