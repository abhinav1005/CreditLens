"""Cost/latency variants report (M4.4-M4.6), generated from saved run summaries.

    uv run python -m evals variants

Reads the runs named below (from reports/ or reports/history/) and writes
reports/cost-variants.md. Every number comes from those files.
"""

import json
from pathlib import Path

from evals.compare import find_run

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "reports" / "cost-variants.md"


def summary(run: str) -> dict:
    return json.loads((find_run(run) / "summary.json").read_text())


def usage(run: str) -> dict:
    rows = [json.loads(line) for line in (find_run(run) / "results.jsonl").read_text().splitlines()]
    return {
        k: sum(r["usage"][k] for r in rows)
        for k in ["input_tokens", "cache_write_tokens", "cache_read_tokens"]
    }


def latency(name: str) -> dict:
    return json.loads((ROOT / "reports" / "latency" / f"{name}.json").read_text())


def render() -> str:
    def pct(s: dict) -> str:
        return f"{100 * s['overall_pass_rate']:.1f}% ({s['n_passed']}/{s['n_cases']})"

    big, small, routed = (
        summary("matrix-claude-sonnet-5-5"),
        summary("matrix-claude-haiku-5-5"),
        summary("routed-golden"),
    )
    off, on = latency("claude-sonnet-5-5"), latency("claude-sonnet-5-5-cache-on")
    s_off, s_on = summary(off["run_id"]), summary(on["run_id"])
    u_off, u_on = usage(off["run_id"]), usage(on["run_id"])
    l2000, l0 = summary("long-budget-2000"), summary("long-budget-0")
    u2000, u0 = usage("long-budget-2000"), usage("long-budget-0")
    lines = [
        "# Cost and latency variants",
        "",
        "Generated by `uv run python -m evals variants` from saved runs. One run per arm, so small differences are noise.",
        "",
        "## Model routing (golden suite, 150 cases, prompt caching off)",
        "",
        "| Strategy | Pass rate | Measured cost |",
        "|---|---:|---:|",
        f"| always big (Sonnet 5.5) | {pct(big)} | ${big['cost']['measured_total_usd']:.2f} |",
        f"| routed (rule router) | {pct(routed)} | ${routed['cost']['measured_total_usd']:.2f} |",
        f"| always small (Haiku 5.5) | {pct(small)} | ${small['cost']['measured_total_usd']:.2f} |",
        "",
        "## Prompt caching (Sonnet 5.5, smoke suite, sequential fresh calls)",
        "",
        "| Caching | Pass rate | Cost | Latency p50 / p95 | TTFT p50 | Input / cache-write / cache-read tokens |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for label, lat, s, u in [("off", off, s_off, u_off), ("on", on, s_on, u_on)]:
        lines.append(
            f"| {label} | {pct(s)} | ${lat['cost_usd']:.3f} | {lat['total_ms']['p50'] / 1000:.1f}s / {lat['total_ms']['p95'] / 1000:.1f}s "
            f"| {lat['ttft_ms']['p50'] / 1000:.1f}s | {u['input_tokens']:,} / {u['cache_write_tokens']:,} / {u['cache_read_tokens']:,} |"
        )
    lines += [
        "",
        "The system prompt contains the profile id, so the cached prefix differs per profile: caching mostly helps inside one turn's tool loop. Moving the id out of the system prompt (a new prompt version) should let the shared prefix be reused across conversations.",
        "",
        "## Context trimming (long-conversation suite, 5 cases with ~5k tokens of history)",
        "",
        "| Budget | Pass rate | Input tokens | Measured cost |",
        "|---|---:|---:|---:|",
        f"| 2,000 tokens (trimming on) | {pct(l2000)} | {u2000['input_tokens']:,} | ${l2000['cost']['measured_total_usd']:.3f} |",
        f"| none (trimming off) | {pct(l0)} | {u0['input_tokens']:,} | ${l0['cost']['measured_total_usd']:.3f} |",
    ]
    return "\n".join(lines) + "\n"


def write() -> Path:
    OUT.write_text(render())
    return OUT
